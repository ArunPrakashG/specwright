import type { SiteSpec } from "@specwright/spec";
import { esc, phpString, themeSlug } from "./util.ts";

const NEWSLETTER_JS = `document.addEventListener("submit", function (event) {
  var form = event.target.closest ? event.target.closest("form.st-form") : null;
  if (!form) return;
  event.preventDefault();
  var note = document.createElement("p");
  note.className = "st-thanks";
  note.setAttribute("role", "status");
  note.textContent = form.getAttribute("data-thanks") || "Thanks, you are on the list.";
  form.replaceWith(note);
});`;

/** functions.php: stylesheet, spec ids on the live markup, and small WooCommerce tweaks. */
export function functionsPhp(spec: SiteSpec) {
  return `<?php
/**
 * ${esc(spec.name)} theme functions. Generated by Specwright from the Site Spec.
 *
 * @package ${themeSlug(spec)}
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Theme supports.
 */
function specwright_setup() {
	add_theme_support( 'woocommerce' );
	remove_theme_support( 'core-block-patterns' );
}
add_action( 'after_setup_theme', 'specwright_setup' );

/**
 * The shared section stylesheet (tokens, section library, WordPress overrides) and the newsletter form script.
 * Enqueued late so it wins ties against global and block styles.
 */
function specwright_assets() {
	$css = get_theme_file_path( 'assets/css/store.css' );
	wp_enqueue_style( 'specwright-store', get_theme_file_uri( 'assets/css/store.css' ), array(), (string) filemtime( $css ) );
	wp_register_script( 'specwright-newsletter', false, array(), '1', array( 'in_footer' => true ) );
	wp_enqueue_script( 'specwright-newsletter' );
	wp_add_inline_script( 'specwright-newsletter', ${phpString(NEWSLETTER_JS)} );
}
add_action( 'wp_enqueue_scripts', 'specwright_assets', 20 );

/**
 * The section library is scoped under .st.
 *
 * @param string[] $classes Body classes.
 * @return string[]
 */
function specwright_body_class( $classes ) {
	$classes[] = 'st';
	return $classes;
}
add_filter( 'body_class', 'specwright_body_class' );

/**
 * Term id of a product category, for product collections in patterns.
 *
 * @param string $slug Category slug.
 * @return int
 */
function specwright_term_id( $slug ) {
	$term = get_term_by( 'slug', $slug, 'product_cat' );
	return $term ? (int) $term->term_id : 0;
}

/**
 * Prices read like the spec: $36, $36.50.
 */
add_filter( 'woocommerce_price_trim_zeros', '__return_true' );

/**
 * Turn sid-* classes into data-spec-id, give the hero button the library's button class,
 * and number product cards (card-1, card-2, …) in render order.
 *
 * @param string $html  Rendered block.
 * @param array  $block Parsed block.
 * @return string
 */
function specwright_spec_ids( $html, $block ) {
	if ( false === strpos( $html, 'sid-' ) && false === strpos( $html, 'sw-cards-' ) ) {
		return $html;
	}
	$p         = new WP_HTML_Tag_Processor( $html );
	$is_button = isset( $block['blockName'] ) && 'core/button' === $block['blockName'];
	$button_id = null;
	$cards     = null;
	$n         = 0;
	while ( $p->next_tag() ) {
		$classes = array();
		foreach ( $p->class_list() as $class ) {
			$classes[] = $class;
		}
		foreach ( $classes as $class ) {
			if ( 0 === strpos( $class, 'sid-' ) ) {
				$p->remove_class( $class );
				$id = str_replace( '__', '.', substr( $class, 4 ) );
				if ( $is_button && in_array( 'wp-block-button', $classes, true ) ) {
					$button_id = $id;
				} else {
					$p->set_attribute( 'data-spec-id', $id );
				}
			} elseif ( 0 === strpos( $class, 'sw-cards-' ) ) {
				$p->remove_class( $class );
				$cards = str_replace( '__', '.', substr( $class, 9 ) );
			}
		}
		if ( $is_button && 'A' === $p->get_tag() && in_array( 'wp-block-button__link', $classes, true ) ) {
			$p->remove_class( 'wp-block-button__link' );
			$p->remove_class( 'wp-element-button' );
			$p->add_class( 'st-btn' );
			if ( $button_id ) {
				$p->set_attribute( 'data-spec-id', $button_id );
			}
		}
		if ( $cards && 'LI' === $p->get_tag() && in_array( 'wc-block-product', $classes, true ) ) {
			++$n;
			$p->add_class( 'st-card' );
			$p->set_attribute( 'data-spec-id', $cards . '.card-' . $n );
		}
		if ( $cards && $n && in_array( 'wc-block-components-product-image', $classes, true ) ) {
			$p->add_class( 'st-tile' );
			$p->set_attribute( 'data-spec-id', $cards . '.card-' . $n . '.image' );
		}
	}
	return $p->get_updated_html();
}
add_filter( 'render_block', 'specwright_spec_ids', 10, 2 );
`;
}
