import { readFile } from "node:fs/promises";
import { basename, join as joinPath } from "node:path";
import type { AdapterContext, Emitted } from "@specwright/core";
import { fontStack, layoutSections, sectionsCss, tokensCss } from "@specwright/sections";
import type { Page, SiteSpec } from "@specwright/spec";
import { block, group, heading, join } from "./blocks.ts";
import { wpCss } from "./css.ts";
import { bundleFonts, type BundledFonts } from "./fonts.ts";
import { functionsPhp } from "./php.ts";
import { productCollection, sectionMarkup } from "./sections.ts";
import { esc, themeSlug, writeTree } from "./util.ts";

export const patternFile = (page: Page, sectionId: string) => `patterns/${page.id}-${sectionId}.php`;

/** Write the block theme to `${outDir}/theme`. Safe to call again while a preview mounts it. */
export async function emitTheme(spec: SiteSpec, ctx: AdapterContext): Promise<Emitted> {
  const dir = joinPath(ctx.outDir, "theme");
  const slug = themeSlug(spec);
  const files = new Map<string, string | Uint8Array>();
  const map: Record<string, string> = {};
  const images = new Set<string>();
  const imageUrl = (src: string) => {
    images.add(src);
    return `<?php echo esc_url( get_theme_file_uri( 'assets/images/${basename(src)}' ) ); ?>`;
  };
  const noImages = () => {
    throw new Error("Header and footer sections cannot reference images in a block theme part");
  };

  const fonts = await bundleFonts(spec, ctx.log, ctx.signal);
  for (const [path, bytes] of fonts.files) files.set(path, bytes);

  const { home, header, footer } = layoutSections(spec);
  const sectionCtx = (page: Page, id: string, image: (src: string) => string, queryId = 1) => ({
    spec,
    page,
    theme: slug,
    queryId,
    id: (part?: string) => (part ? `${page.id}.${id}.${part}` : `${page.id}.${id}`),
    image,
  });
  if (header) {
    files.set("parts/header.html", sectionMarkup(header, sectionCtx(home, header.id, noImages)) + "\n");
    map[`${home.id}.${header.id}`] = "parts/header.html";
  } else files.set("parts/header.html", "\n");
  if (footer) {
    files.set("parts/footer.html", sectionMarkup(footer, sectionCtx(home, footer.id, noImages)) + "\n");
    map[`${home.id}.${footer.id}`] = "parts/footer.html";
  } else files.set("parts/footer.html", "\n");

  const pagePatterns = new Map<string, string[]>();
  for (const page of spec.pages) {
    const slugs: string[] = [];
    page.sections.forEach((s, i) => {
      if (s.type === "header" || s.type === "footer") return;
      const file = patternFile(page, s.id);
      const markup = sectionMarkup(s, sectionCtx(page, s.id, imageUrl, i + 1));
      files.set(file, patternPhp(spec, page, s.id, markup));
      map[`${page.id}.${s.id}`] = file;
      slugs.push(`${slug}/${page.id}-${s.id}`);
    });
    pagePatterns.set(page.id, slugs);
  }

  for (const src of images) files.set(`assets/images/${basename(src)}`, await readFile(joinPath(ctx.specDir, src)));

  files.set("style.css", styleCss(spec));
  files.set("theme.json", JSON.stringify(themeJson(spec, fonts), null, 2) + "\n");
  files.set("functions.php", functionsPhp(spec));
  files.set("assets/css/store.css", `${tokensCss(spec, ".st")}\n${sectionsCss}\n${wpCss}`);
  for (const [name, body] of Object.entries(templates(pagePatterns.get(home.id) ?? []))) files.set(`templates/${name}.html`, body + "\n");

  const written = await writeTree(dir, files);
  const patterns = written.filter((f) => f.startsWith("patterns/")).length;
  ctx.log(`Theme ${slug}: ${written.length} files, ${patterns} patterns${fonts.faces.length ? `, ${fonts.files.size} font files` : ", system fonts"}`);
  return { dir, files: written, map, summary: `${written.length} files · ${patterns} patterns` };
}

function patternPhp(spec: SiteSpec, page: Page, sectionId: string, markup: string) {
  return `<?php
/**
 * Title: ${esc(page.title)}: ${sectionId}
 * Slug: ${themeSlug(spec)}/${page.id}-${sectionId}
 * Inserter: no
 *
 * @package ${themeSlug(spec)}
 */

?>
${markup}
`;
}

function styleCss(spec: SiteSpec) {
  return `/*
Theme Name: ${spec.name}
${spec.domain ? `Theme URI: https://${spec.domain}/\n` : ""}Author: Specwright
Description: Block theme for ${spec.name}, generated by Specwright from the Site Spec (revision ${spec.revision}). Edit the spec, not these files.
Requires at least: 6.7
Tested up to: 7.1
Requires PHP: 7.4
Version: ${spec.revision}.0.0
License: GNU General Public License v2 or later
License URI: http://www.gnu.org/licenses/gpl-2.0.html
Text Domain: ${themeSlug(spec)}
Tags: block-patterns, full-site-editing, e-commerce
*/
`;
}

function themeJson(spec: SiteSpec, fonts: BundledFonts) {
  const family = (slug: "heading" | "body", name: string) => {
    const faces = fonts.faces.filter((f) => f.fontFamily === name);
    return {
      slug,
      name,
      fontFamily: fontStack(name),
      ...(faces.length
        ? {
            fontFace: faces.map((f) => ({
              fontFamily: f.fontFamily,
              fontStyle: f.fontStyle,
              fontWeight: f.fontWeight,
              fontDisplay: "swap",
              src: [`file:./${f.file}`],
              ...(f.unicodeRange ? { unicodeRange: f.unicodeRange } : {}),
            })),
          }
        : {}),
    };
  };
  const preset = (kind: string, slug: string) => `var(--wp--preset--${kind}--${slug})`;
  return {
    $schema: "https://schemas.wp.org/trunk/theme.json",
    version: 3,
    settings: {
      appearanceTools: false,
      color: {
        defaultPalette: false,
        defaultGradients: false,
        defaultDuotone: false,
        palette: Object.entries(spec.tokens.color).map(([slug, color]) => ({ slug, color, name: slug })),
      },
      typography: {
        defaultFontSizes: false,
        fluid: false,
        fontFamilies: [family("heading", spec.tokens.font.heading), family("body", spec.tokens.font.body)],
      },
      layout: { contentSize: `${spec.tokens.width}px`, wideSize: `${spec.tokens.width + 80}px` },
      spacing: { blockGap: true },
    },
    styles: {
      color: { background: preset("color", "bg"), text: preset("color", "ink") },
      typography: { fontFamily: preset("font-family", "body") },
      spacing: { blockGap: "0px" },
      elements: {
        link: { color: { text: preset("color", "ink") } },
        heading: { typography: { fontFamily: preset("font-family", "heading"), fontWeight: "400" } },
        button: {
          color: { background: preset("color", "primary"), text: preset("color", "on-primary") },
          border: { radius: `${spec.tokens.radius}px` },
          typography: { fontFamily: preset("font-family", "body"), fontWeight: "500", fontSize: "15px" },
        },
      },
    },
    templateParts: [
      { name: "header", title: "Header", area: "header" },
      { name: "footer", title: "Footer", area: "footer" },
    ],
  };
}

const part = (slug: string) => block("template-part", { slug, tagName: "div" });
const frame = (main: string) => join(part("header"), main, part("footer"));
const main = (className: string, inner: string) => group(className, inner, { tag: "main", anchor: "main" });
const notices = block("woocommerce/store-notices");

function archive(title: string) {
  const extra = join(
    block("query-pagination", { layout: { type: "flex", justifyContent: "center" }, className: "st-pagination" }, join(block("query-pagination-previous"), block("query-pagination-numbers"), block("query-pagination-next"))),
    block("woocommerce/product-collection-no-results", null, group("", block("paragraph", null, "<p>No products found.</p>"))),
  );
  return frame(
    main(
      "st-in st-shop",
      join(
        title,
        notices,
        group("st-shop-bar", join(block("woocommerce/product-results-count"), block("woocommerce/catalog-sorting"))),
        productCollection({ queryId: 1, perPage: 12, inherit: true, extra }),
      ),
    ),
  );
}

function templates(homePatterns: string[]): Record<string, string> {
  const pageContent = block("post-content", { layout: { type: "default" } });
  const shopTitle = block("query-title", { type: "archive", showPrefix: false, level: 1, className: "st-h2 st-shop-title" });
  const wcPage = (page: string, withTitle: boolean) =>
    frame(
      block(
        "woocommerce/page-content-wrapper",
        { page },
        main("st-in st-shop", join(notices, withTitle && block("post-title", { level: 1, className: "st-h2 st-shop-title" }), pageContent)),
      ),
    );
  return {
    "front-page": frame(main("st-front", join(...homePatterns.map((slug) => block("pattern", { slug }))))),
    index: frame(
      main(
        "st-in st-shop",
        join(
          heading(1, "st-h2 st-shop-title", "Journal"),
          block(
            "query",
            { queryId: 1, query: { perPage: 10, pages: 0, offset: 0, postType: "post", order: "desc", orderBy: "date", inherit: true } },
            `<div class="wp-block-query">\n${join(
              block("post-template", null, join(block("post-title", { isLink: true, level: 2, className: "st-h2" }), block("post-excerpt"))),
              block("query-pagination", null, join(block("query-pagination-previous"), block("query-pagination-next"))),
              block("query-no-results", null, block("paragraph", null, "<p>Nothing here yet.</p>")),
            )}\n</div>`,
          ),
        ),
      ),
    ),
    page: frame(main("st-page", pageContent)),
    single: frame(
      main("st-in st-shop", group("st-prose", join(block("post-title", { level: 1, className: "st-h2" }), pageContent), { tag: "article" })),
    ),
    "404": frame(main("st-in st-shop", group("st-prose", join(heading(1, "st-h2", "Page not found"), block("paragraph", null, `<p><a href="/">Back to the home page</a></p>`))))),
    "archive-product": archive(shopTitle),
    "taxonomy-product_cat": archive(shopTitle),
    "taxonomy-product_tag": archive(shopTitle),
    "product-search-results": archive(shopTitle),
    "single-product": frame(
      main(
        "st-in st-shop",
        join(
          notices,
          block("woocommerce/breadcrumbs"),
          block(
            "columns",
            { className: "st-product" },
            `<div class="wp-block-columns st-product">\n${join(
              block("column", null, `<div class="wp-block-column">\n${block("woocommerce/product-image-gallery")}\n</div>`),
              block(
                "column",
                { className: "st-product-summary" },
                `<div class="wp-block-column st-product-summary">\n${join(
                  block("post-title", { level: 1, className: "st-h2", __woocommerceNamespace: "woocommerce/product-query/product-title" }),
                  block("woocommerce/product-price", { isDescendentOfSingleProductTemplate: true }),
                  block("post-excerpt", { __woocommerceNamespace: "woocommerce/product-query/product-summary", excerptLength: 100 }),
                  block("woocommerce/add-to-cart-form"),
                  block(
                    "woocommerce/product-meta",
                    null,
                    `<div class="wp-block-woocommerce-product-meta">\n${block("woocommerce/product-sku")}\n</div>`,
                  ),
                )}\n</div>`,
              ),
            )}\n</div>`,
          ),
          block("woocommerce/product-details", { className: "st-product-details" }),
        ),
      ),
    ),
    "page-cart": wcPage("cart", true),
    "page-checkout": wcPage("checkout", true),
    "order-confirmation": frame(
      main(
        "st-in st-shop",
        join(
          block("woocommerce/order-confirmation-status", { className: "st-h2" }),
          block("woocommerce/order-confirmation-summary"),
          block("woocommerce/order-confirmation-totals-wrapper", null, join(heading(2, "st-h2", "Order details"), block("woocommerce/order-confirmation-totals"))),
          block("woocommerce/order-confirmation-downloads-wrapper", null, join(heading(2, "st-h2", "Downloads"), block("woocommerce/order-confirmation-downloads"))),
          block(
            "woocommerce/order-confirmation-shipping-wrapper",
            null,
            join(heading(2, "st-h2", "Shipping address"), block("woocommerce/order-confirmation-shipping-address")),
          ),
          block(
            "woocommerce/order-confirmation-billing-wrapper",
            null,
            join(heading(2, "st-h2", "Billing address"), block("woocommerce/order-confirmation-billing-address")),
          ),
          block("woocommerce/order-confirmation-additional-information"),
        ),
      ),
    ),
  };
}

